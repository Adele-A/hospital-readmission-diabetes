"""Run the SQL data-quality audit and write reports/data_quality_report.md.

Executes the named queries in ``sql/02_quality_checks.sql`` plus two computed
checks (per-column missingness and numeric-feature ranges) and assembles a
Markdown report. Every number in the report comes straight from DuckDB.

Run:  python -m src.data.quality_audit
"""

from __future__ import annotations

import re

import duckdb
import pandas as pd

from src.config import load_config
from src.data.load import build_database, connect
from src.paths import repo_path

# Continuous numeric features whose ranges we sanity-check.
NUMERIC_COLUMNS = [
    "time_in_hospital",
    "num_lab_procedures",
    "num_procedures",
    "num_medications",
    "number_outpatient",
    "number_emergency",
    "number_inpatient",
    "number_diagnoses",
]


def parse_named_queries(sql_text: str) -> dict[str, str]:
    """Split a .sql file into {name: query} using ``-- name: <key>`` tags."""
    queries: dict[str, str] = {}
    current: str | None = None
    buf: list[str] = []
    for line in sql_text.splitlines():
        tag = re.match(r"^--\s*name:\s*(\w+)", line.strip())
        if tag:
            if current and buf:
                queries[current] = "\n".join(buf).strip()
            current = tag.group(1)
            buf = []
        elif current:
            buf.append(line)
    if current and buf:
        queries[current] = "\n".join(buf).strip()
    # Drop trailing comment-only remnants.
    return {k: v for k, v in queries.items() if v and not v.startswith("--") or ";" in v}


def df_to_md(df: pd.DataFrame) -> str:
    """Render a DataFrame as a GitHub Markdown table."""
    cols = list(df.columns)
    head = "| " + " | ".join(str(c) for c in cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    body = [
        "| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |"
        for row in df.itertuples(index=False, name=None)
    ]
    return "\n".join([head, sep, *body])


def column_missingness(con: duckdb.DuckDBPyConnection) -> pd.DataFrame:
    """Count '?' per column across encounters_raw (one UNION ALL query)."""
    cols = [r[0] for r in con.execute("DESCRIBE encounters_raw;").fetchall()]
    total = con.execute("SELECT count(*) FROM encounters_raw;").fetchone()[0]
    parts = [
        f"SELECT '{c}' AS column, "
        f"CAST(sum(CASE WHEN \"{c}\" = '?' THEN 1 ELSE 0 END) AS BIGINT) AS n_missing"
        f" FROM encounters_raw"
        for c in cols
    ]
    df = con.execute(" UNION ALL ".join(parts)).df()
    df["pct_missing"] = (100.0 * df["n_missing"] / total).round(2)
    return df[df["n_missing"] > 0].sort_values("n_missing", ascending=False).reset_index(drop=True)


def numeric_ranges(con: duckdb.DuckDBPyConnection) -> pd.DataFrame:
    """min / max / mean / stddev for continuous numeric features."""
    parts = [
        f"SELECT '{c}' AS feature, min(CAST(\"{c}\" AS DOUBLE)) AS min, "
        f"max(CAST(\"{c}\" AS DOUBLE)) AS max, round(avg(CAST(\"{c}\" AS DOUBLE)), 2) AS mean, "
        f"round(stddev_samp(CAST(\"{c}\" AS DOUBLE)), 2) AS stddev "
        f"FROM encounters_raw"
        for c in NUMERIC_COLUMNS
    ]
    return con.execute(" UNION ALL ".join(parts)).df()


def _scalar(con: duckdb.DuckDBPyConnection, query: str):
    return con.execute(query).fetchone()


def build_report(con: duckdb.DuckDBPyConnection) -> str:
    sql_text = repo_path("sql", "02_quality_checks.sql").read_text(encoding="utf-8")
    q = parse_named_queries(sql_text)

    n_enc = con.execute(q["row_count"]).fetchone()[0]
    n_pat = con.execute(q["unique_patients"]).fetchone()[0]
    n_dup = con.execute(q["duplicate_encounter_ids"]).fetchone()[0]

    epp = con.execute(q["encounters_per_patient"]).df()
    readmit = con.execute(q["readmitted_distribution"]).df()
    gender = con.execute(q["gender_distribution"]).df()
    a1c = con.execute(q["a1cresult_distribution"]).df()
    glu = con.execute(q["max_glu_serum_distribution"]).df()
    death = con.execute(q["death_hospice_discharges"]).df()
    miss = column_missingness(con)
    ranges = numeric_ranges(con)

    death_total = int(death["n"].sum()) if not death.empty else 0
    pos = readmit.loc[readmit["readmitted"] == "<30", "n"]
    pos_n = int(pos.iloc[0]) if len(pos) else 0
    pos_pct = round(100.0 * pos_n / n_enc, 2)

    lines = [
        "# Data Quality Report — Diabetes 130-US (Stage 1)",
        "",
        "Automatically generated by `src/data/quality_audit.py` from the raw CSVs "
        "loaded into DuckDB. Every figure is reproducible via `python -m src.data.quality_audit`.",
        "",
        "## 1. Size and identifiers",
        "",
        f"- **Encounters (rows):** {n_enc:,}",
        f"- **Unique patients (`patient_nbr`):** {n_pat:,}",
        f"- **Duplicate `encounter_id`:** {n_dup} "
        f"({'none — encounter_id is a valid primary key' if n_dup == 0 else 'see below'})",
        "",
        "Rows are **encounters, not patients** — one patient may have several encounters, "
        "so all splitting later is done by `patient_nbr` to avoid leakage.",
        "",
        "### Encounters per patient",
        "",
        df_to_md(epp),
        "",
        "## 2. Target variable (`readmitted`)",
        "",
        df_to_md(readmit),
        "",
        f"Modelling target: `y = 1` if `readmitted == \"<30\"` else `0`. "
        f"Positive (`<30`) encounters: **{pos_n:,} ({pos_pct}%)** of all rows — "
        "a ~1:8 class imbalance, handled without oversampling (calibration reported).",
        "",
        "## 3. Exclusions preview — death / hospice discharges",
        "",
        "`discharge_disposition_id` codes meaning death or hospice (verified against "
        "`IDS_mapping.csv`). These encounters cannot be readmitted and are excluded in Stage 2.",
        "",
        df_to_md(death),
        "",
        f"**Total to exclude for death/hospice:** {death_total:,} encounters.",
        "",
        "## 4. Gender",
        "",
        df_to_md(gender),
        "",
        "`Unknown/Invalid` gender (a handful of rows) is dropped in Stage 2 "
        "(configurable via `cohort.drop_gender_unknown`).",
        "",
        "## 5. `A1Cresult` and `max_glu_serum` — \"None\" is a real category",
        "",
        "The string `None` means *the test was not performed* — a meaningful category, "
        "not missing data. CSV reads use `na_values=[\"?\"]` only.",
        "",
        "**A1Cresult:**",
        "",
        df_to_md(a1c),
        "",
        "**max_glu_serum:**",
        "",
        df_to_md(glu),
        "",
        "## 6. Missingness (`?`) by column",
        "",
        "Only columns with at least one `?` are listed.",
        "",
        df_to_md(miss),
        "",
        "Decisions (approved): `weight` dropped (~97% missing); `medical_specialty` and "
        "`payer_code` kept as an explicit `Missing` category with rare levels grouped "
        "(`payer_code` is administrative — flagged in Limitations).",
        "",
        "## 7. Numeric feature ranges",
        "",
        df_to_md(ranges),
        "",
        "No negative counts or impossible values observed; ranges are consistent with "
        "the dataset documentation.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    cfg = load_config()
    con = connect(cfg)
    try:
        # Ensure tables exist / are fresh.
        if not con.execute(
            "SELECT count(*) FROM information_schema.tables WHERE table_name = 'encounters_raw';"
        ).fetchone()[0]:
            build_database(con, cfg)
        report = build_report(con)
    finally:
        con.close()

    out = repo_path(cfg["paths"]["reports_dir"], "data_quality_report.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8", newline="\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
