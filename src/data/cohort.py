"""Stage 2 — cohort definition, target variable, and CONSORT-style exclusion flow.

Applies the frozen exclusions (death/hospice discharge, Unknown/Invalid gender),
defines the binary target ``y`` (readmitted ``<30`` vs everything else), flags the
first encounter per patient for the sensitivity analysis, and records how many
encounters and patients remain after each step.

Outputs:
  - DuckDB table ``cohort`` (primary = all eligible encounters).
  - ``reports/cohort_flow.md``   — the exclusion-flow table.
  - ``reports/figures/exclusion_flow.png`` — the CONSORT-style diagram.

Run:  python -m src.data.cohort
"""

from __future__ import annotations

from pathlib import Path

import duckdb
import pandas as pd

from src.config import load_config
from src.data.load import build_database, connect
from src.paths import repo_path


def exclusion_predicates(cfg: dict) -> list[tuple[str, str | None]]:
    """Ordered (label, cumulative-predicate) exclusion steps. None = no filter."""
    death_ids = ", ".join(str(i) for i in cfg["cohort"]["death_hospice_discharge_ids"])
    steps: list[tuple[str, str | None]] = [("All encounters (raw)", None)]
    steps.append(
        (
            "Exclude death / hospice discharge disposition",
            f"CAST(discharge_disposition_id AS INTEGER) NOT IN ({death_ids})",
        )
    )
    if cfg["cohort"].get("drop_gender_unknown", True):
        steps.append(("Exclude gender = Unknown/Invalid", "gender <> 'Unknown/Invalid'"))
    return steps


def exclusion_flow(con: duckdb.DuckDBPyConnection, cfg: dict) -> pd.DataFrame:
    """Compute encounters/patients remaining after each cumulative exclusion."""
    steps = exclusion_predicates(cfg)
    predicates: list[str] = []
    rows = []
    prev_enc = prev_pat = None
    for label, pred in steps:
        if pred is not None:
            predicates.append(pred)
        where = (" WHERE " + " AND ".join(predicates)) if predicates else ""
        n_enc, n_pat = con.execute(
            f"SELECT count(*), count(DISTINCT patient_nbr) FROM encounters_raw{where};"
        ).fetchone()
        rows.append(
            {
                "step": label,
                "encounters_remaining": n_enc,
                "patients_remaining": n_pat,
                "encounters_removed": 0 if prev_enc is None else prev_enc - n_enc,
                "patients_removed": 0 if prev_pat is None else prev_pat - n_pat,
            }
        )
        prev_enc, prev_pat = n_enc, n_pat
    return pd.DataFrame(rows)


def build_cohort_table(con: duckdb.DuckDBPyConnection, cfg: dict) -> None:
    """(Re)create the ``cohort`` table with target and first-encounter flag."""
    steps = exclusion_predicates(cfg)
    predicates = [p for _, p in steps if p is not None]
    where = (" WHERE " + " AND ".join(predicates)) if predicates else ""
    pos = cfg["cohort"]["positive_label"]
    con.execute("DROP TABLE IF EXISTS cohort;")
    con.execute(
        f"""
        CREATE TABLE cohort AS
        SELECT
            *,
            CASE WHEN readmitted = '{pos}' THEN 1 ELSE 0 END AS y,
            (row_number() OVER (PARTITION BY patient_nbr
                                ORDER BY CAST(encounter_id AS BIGINT)) = 1)
                AS is_first_encounter
        FROM encounters_raw{where};
        """
    )


def _flow_to_md(flow: pd.DataFrame, cfg: dict) -> str:
    final = flow.iloc[-1]
    lines = [
        "# Cohort exclusion flow (CONSORT-style)",
        "",
        "Generated by `src/data/cohort.py`. Primary analytic cohort = all eligible encounters.",
        "",
        "| step | encounters | patients | encounters removed | patients removed |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for r in flow.itertuples(index=False):
        lines.append(
            f"| {r.step} | {r.encounters_remaining:,} | {r.patients_remaining:,} | "
            f"{r.encounters_removed:,} | {r.patients_removed:,} |"
        )
    lines += [
        "",
        f"**Analytic cohort:** {final.encounters_remaining:,} encounters "
        f"from {final.patients_remaining:,} patients.",
        "",
        "See `reports/figures/exclusion_flow.png` for the diagram and "
        "`docs/cohort_definition.md` for the full definition.",
        "",
    ]
    return "\n".join(lines)


def render_flow_figure(flow: pd.DataFrame, out_path: Path) -> None:
    """Draw a simple vertical CONSORT-style flow diagram."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    n = len(flow)
    fig, ax = plt.subplots(figsize=(8.5, 2.2 * n))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, n)
    ax.axis("off")

    box = dict(boxstyle="round,pad=0.5", facecolor="#eef3fb", edgecolor="#3b5b92", linewidth=1.5)
    excl = dict(boxstyle="round,pad=0.4", facecolor="#fdecec", edgecolor="#b23b3b", linewidth=1.2)

    for i, r in enumerate(flow.itertuples(index=False)):
        y = n - 0.5 - i
        is_last = i == n - 1
        if is_last:
            title = "Analytic cohort"
        elif i == 0:
            title = r.step
        else:
            title = r.step.replace("Exclude ", "After excluding ")
        ax.text(
            3.2,
            y,
            f"{title}\n{r.encounters_remaining:,} encounters\n{r.patients_remaining:,} patients",
            ha="center",
            va="center",
            fontsize=10,
            bbox=box,
        )
        if i > 0:
            ax.annotate(
                "",
                xy=(3.2, y + 0.42),
                xytext=(3.2, y + 0.58),
                arrowprops=dict(arrowstyle="-|>", color="#3b5b92", lw=1.5),
            )
            ax.text(
                7.0,
                y + 0.5,
                f"Excluded: {r.step.replace('Exclude ', '')}\n"
                f"−{r.encounters_removed:,} encounters",
                ha="center",
                va="center",
                fontsize=8.5,
                bbox=excl,
            )
            ax.annotate(
                "",
                xy=(5.6, y + 0.5),
                xytext=(4.6, y + 0.5),
                arrowprops=dict(arrowstyle="-|>", color="#b23b3b", lw=1.2),
            )

    fig.suptitle("Diabetes 130-US — cohort exclusion flow", fontsize=12, y=0.99)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    cfg = load_config()
    con = connect(cfg)
    try:
        if not con.execute(
            "SELECT count(*) FROM information_schema.tables WHERE table_name = 'encounters_raw';"
        ).fetchone()[0]:
            build_database(con, cfg)
        flow = exclusion_flow(con, cfg)
        build_cohort_table(con, cfg)
        n_cohort, n_pat, n_pos = con.execute(
            "SELECT count(*), count(DISTINCT patient_nbr), sum(y) FROM cohort;"
        ).fetchone()
        n_first = con.execute(
            "SELECT count(*) FROM cohort WHERE is_first_encounter;"
        ).fetchone()[0]
    finally:
        con.close()

    reports = repo_path(cfg["paths"]["reports_dir"])
    (reports / "cohort_flow.md").write_text(_flow_to_md(flow, cfg), encoding="utf-8", newline="\n")
    render_flow_figure(flow, reports / "figures" / "exclusion_flow.png")

    print(flow.to_string(index=False))
    print(
        f"\nCohort: {n_cohort:,} encounters, {n_pat:,} patients, "
        f"{int(n_pos):,} positives ({100.0 * n_pos / n_cohort:.2f}%). "
        f"First-encounter rows: {n_first:,}."
    )


if __name__ == "__main__":
    main()
